/**
 * The PackML standard-interface catalog. `interface` is intentionally absent:
 * the standard describes the interface, each machine supplies its own server.
 * The illustrative NodeIds use the conventional `ns=4;s=<path>` form.
 */
export function packMlBook(): AddressBook {
  const entries: BookEntry[] = PACKML_TAGS.map((tag) => ({
    path: tag.path,
    sourceType: tag.dataType,
    leafType: opcUaLeafType(tag.dataType),
    access: tag.access,
    // Reference shown with a neutral connection placeholder; the real one is the
    // machine's OPC UA connection, injected at check-in.
    addresses: { opcua: buildOpcUaReference('<Machine>', `ns=4;s=${tag.path}`) },
    comment: tag.comment,
    unit: tag.unit
  }));
  return {
    id: 'book-packml-v101',
    name: 'PackML v1.01 (interface OPC UA standard)',
    provenance: {
      kind: 'nodeset',
      file: 'Opc.Ua.PackML.NodeSet2.xml',
      generatedAt: '2026-07-10T11:30:00.000Z',
      detail: 'OPC 30050 « OPC UA for PackML » / OMAC ISA-TR88.00.02 — PackTags Command · Status · Admin'
    },
    // interface intentionally absent → standard interface, bound per machine.
    entries,
    types: [
      {
        id: 'PackMLStatusObjectType',
        name: 'PackMLStatusObjectType',
        members: PACKML_TAGS.filter((t) => t.path.startsWith('Status.')).map((t) => ({
          path: t.path.slice('Status.'.length),
          sourceType: t.dataType,
          leafType: opcUaLeafType(t.dataType),
          comment: t.comment
        }))
      },
      {
        id: 'PackMLAdminObjectType',
        name: 'PackMLAdminObjectType',
        members: PACKML_TAGS.filter((t) => t.path.startsWith('Admin.')).map((t) => ({
          path: t.path.slice('Admin.'.length),
          sourceType: t.dataType,
          leafType: opcUaLeafType(t.dataType),
          comment: t.comment
        }))
      }
    ],
    warnings: [
      warn(
        'demo.packml-subset',
        'A representative SUBSET of PackTags (the OPC 30050 spec could not be opened directly) — recalibrate it with a browse of the machine, or by ingesting the spec NodeSet2.'
      ),
      warn('demo.packml-illustrative-nodeids', 'The NodeIds are illustrative (ns=4;s=…): the real namespace depends on the machine OPC UA server.')
    ]
  };
}
