/**
 * PackML (OMAC / ISA-TR88.00.02) — STANDARD OPC UA interface catalog.
 *
 * The archetype of a mutualised book: PackML defines standard tag names and
 * values for packaging machines, so ONE catalog describes the interface of every
 * PackML-compliant machine of a line. The book therefore carries **no
 * `interface`** — it is the standard itself, bound to each machine's own OPC UA
 * server at check-in (many-to-many book relation).
 *
 * PackTags are grouped in three sets (ISA-TR88.00.02):
 *   - **Command** — drive the state machine and the machine's general behaviour
 *     (in OPC UA these are often exposed as Methods as well as variables);
 *   - **Status**  — current state/mode/speed and interlocks;
 *   - **Admin**   — counters, times, alarms and stop reasons.
 *
 * SOURCES: OPC Foundation "OPC UA for PackML — Common Object Model" (OPC 30050,
 * PackMLStatusObjectType / PackMLAdminObjectType / Command tags) and the OMAC
 * PackML Unit/Machine Implementation Guide; tag names cross-checked against a
 * vendor implementation (Schneider EIO0000002202) — `StateCurrent` DINT,
 * `UnitModeCurrent` DINT, `CurMachSpeed` REAL.
 *
 * ⚠️ PARTIAL/UNVERIFIED: the OPC Foundation reference pages could not be opened
 * directly (HTTP 403), so this catalog is a faithful but NON-EXHAUSTIVE subset
 * of PackTags, and the OPC UA NodeIds below are illustrative (`ns=4;s=…`) — a
 * real book is generated by browsing the machine's server or by ingesting the
 * companion-spec NodeSet2. Re-calibrate against the machine before check-in.
 *
 * PackML state model values (ISA-TR88.00.02), for reference:
 *   1 CLEARING · 2 STOPPED · 3 STARTING · 4 IDLE · 5 SUSPENDED · 6 EXECUTE ·
 *   7 STOPPING · 8 ABORTING · 9 ABORTED · 10 HOLDING · 11 HELD · 12 UNHOLDING ·
 *   13 SUSPENDING · 14 UNSUSPENDING · 15 RESETTING · 16 COMPLETING · 17 COMPLETE
 * UnitMode: 1 PRODUCTION · 2 MAINTENANCE · 3 MANUAL.
 * CntrlCmd: 1 RESET · 2 START · 3 STOP · 4 HOLD · 5 UNHOLD · 6 SUSPEND ·
 *   7 UNSUSPEND · 8 ABORT · 9 CLEAR.
 */

